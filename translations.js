// ===== APPLY LANGUAGE =====
function applyLanguage(lang) {
  const t = TRANSLATIONS[lang] || TRANSLATIONS.ru;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.placeholder = t[key];
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (t[key] !== undefined) el.title = t[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (t[key] !== undefined) el.setAttribute('aria-label', t[key]);
  });
  // Document title
  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) {
    const key = titleEl.getAttribute('data-i18n');
    if (t[key] !== undefined) document.title = t[key];
  }
  document.documentElement.lang = lang;
  document.documentElement.setAttribute('data-lang', lang);
  try { localStorage.setItem('klever_lang', lang); } catch(e) {}
  // Update active flag in switcher
  document.querySelectorAll('.klever-lang-opt').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
  const currentFlag = document.querySelector('.klever-lang-current-flag');
  const currentCode = document.querySelector('.klever-lang-current-code');
  const FLAGS = { ru: '🇷🇺', en: '🇬🇧', zh: '🇨🇳', ko: '🇰🇷' };
  const CODES = { ru: 'RU', en: 'EN', zh: 'ZH', ko: 'KO' };
  if (currentFlag) currentFlag.textContent = FLAGS[lang] || FLAGS.ru;
  if (currentCode) currentCode.textContent = CODES[lang] || CODES.ru;
}

function getSavedLang() {
  try { return localStorage.getItem('klever_lang') || 'ru'; } catch(e) { return 'ru'; }
}

if (typeof window !== 'undefined') {
  window.TRANSLATIONS = TRANSLATIONS;
  window.applyLanguage = applyLanguage;
  window.getSavedLang = getSavedLang;
}
